CREATE TYPE public.app_role AS ENUM ('admin', 'moderator', 'user');
CREATE TABLE public.user_roles (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE, role public.app_role NOT NULL, UNIQUE(user_id, role));
GRANT SELECT ON public.user_roles TO authenticated;
GRANT ALL ON public.user_roles TO service_role;
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;
CREATE FUNCTION public.has_role(_user_id uuid, _role public.app_role) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$ SELECT EXISTS(SELECT 1 FROM public.user_roles WHERE user_id = _user_id AND role = _role) $$;
CREATE POLICY "Read own roles" ON public.user_roles FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE TABLE public.booking_inquiries (id uuid PRIMARY KEY, fields jsonb NOT NULL, event_style jsonb NOT NULL DEFAULT '{}'::jsonb, created_at timestamptz NOT NULL DEFAULT now());
GRANT SELECT ON public.booking_inquiries TO authenticated;
GRANT ALL ON public.booking_inquiries TO service_role;
ALTER TABLE public.booking_inquiries ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Admins read booking inquiries" ON public.booking_inquiries FOR SELECT TO authenticated USING(public.has_role(auth.uid(), 'admin'));
ALTER TABLE public.bookings ADD COLUMN event_style jsonb NOT NULL DEFAULT '{}'::jsonb;
DROP POLICY "Anyone can read bookings" ON public.bookings;
CREATE POLICY "Admins read bookings" ON public.bookings FOR SELECT TO authenticated USING(public.has_role(auth.uid(), 'admin'));
GRANT SELECT ON public.bookings TO authenticated;
CREATE POLICY "Admins view inspiration photos" ON storage.objects FOR SELECT TO authenticated USING (bucket_id = 'booking-inspiration' AND public.has_role(auth.uid(), 'admin'));
